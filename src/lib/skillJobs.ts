/**
 * スキル横断のジョブ台帳「型契約」(SQ1 / 2026-08-04)。
 *
 * ## これは何か
 *
 * 「1つのスキルで同じ生成を何本も並べて走らせる」ときの、フロント側データ構造の**型だけ**の合意。
 * 実行コード・ランタイム基盤はここに置かない (置くと 2 例目が無いまま抽象が固まる)。
 * 最初の実装は characterSheetRun.ts で、この契約を満たす形で書かれている。
 *
 * ## 中核の考え方: 入力(下書き)とジョブを別の寿命にする
 *
 * - **下書き (draft)** は常に 1 つで、いつでも編集できる。画面の入力欄そのもの。
 * - **ジョブ (job)** は「生成する」を押した瞬間に、そのときの下書きを**凍結コピー**して生まれる。
 *   以後ジョブの入力は不変。だから走行中に下書きを書き換えても、走っているジョブの
 *   登録内容は変わらない (旧実装ではストアの現在値を読んでいたため変わってしまった)。
 *
 * ## 並走数はフロントで制御しない
 *
 * 確定した瞬間に invoke し、順番待ちは Rust 側のセマフォに任せる。
 * フロントに待機キューを作ると「完了イベントを取りこぼすとキューが永久停止する」という
 * 新しい壊れ方を持ち込むため。上限の正本は Rust 側にしか置かない。
 */

/** ジョブの生存状態。台帳から消える (dismiss/complete) のは status とは別軸。 */
export type SkillJobStatus = "running" | "completed" | "failed";

/**
 * 1 本の生成ジョブ。
 *
 * @typeParam TInput - 確定時に凍結する入力のスナップショット型。以後不変として扱う。
 * @typeParam TCut - このジョブが持つカット 1 枚の状態型。
 */
export type SkillJob<TInput, TCut> = {
  /**
   * 安定キー。ジョブが生きている間ずっと不変。
   * 再生成しても変わらない (変わるのは activeRunId のほう)。
   */
  jobId: string;
  /**
   * このジョブを作ったスキル。1 つのストアを複数スキルで共有する場合の判別子。
   * イベントから状態を書く際、ストアの「現在のモード」ではなく**ジョブ自身のこの値**を見る
   * (モード切替中に届いた後着イベントで種別を取り違えないため)。
   */
  jobMode: string;
  /**
   * 現在の run。再生成すると新しい runId に差し替わり、旧 runId は逆引き表から外れる
   * (＝旧 run の後着イベントは行き先を失って構造的に落ちる)。
   */
  activeRunId: string;
  /** 確定時に凍結した入力。以後書き換えない。 */
  input: TInput;
  /** cutId → カット状態。 */
  cuts: Record<string, TCut>;
  /** 表示順 (確定時に固定)。 */
  cutOrder: string[];
  /** cutId → 実際に生成が始まった時刻 (epoch ms)。ゲージの起点。 */
  cutStartedAt: Record<string, number>;
  status: SkillJobStatus;
  createdAt: number;
};

/**
 * ジョブ台帳を持つストアの共通形。
 *
 * `runIndex` が要点: イベントは runId しか持たないので、これで jobId へ引く。
 * ここに載っていない runId のイベントは**必ず捨てる** (終了・再生成・モード切替で
 * 外した run の後着通知が、別のジョブの状態を上書きするのを防ぐ)。
 */
export type SkillJobLedger<TJob> = {
  jobs: Record<string, TJob>;
  /** 仕込み順。表示順序の正本。 */
  jobOrder: string[];
  /** runId → jobId。イベントの一次ルーティング表。 */
  runIndex: Record<string, string>;
  /** いま画面が見ているジョブ。null = 未選択。 */
  focusedJobId: string | null;
};

/**
 * アクション命名の規約 (実装側が従う約束。ここでは型を強制しない)。
 *
 * - `submit`  — 下書きを凍結してジョブを作り、**即ディスパッチ**する。待機キューは作らない。
 * - `focus`   — 画面が見るジョブを切り替える。
 * - `dismiss` — 未完了ジョブを台帳から外す (中止・破棄)。run は逆引き表から外して墓標化する。
 * - `complete`— 成果を確定して台帳から外す (登録完了)。**下書きには触らない**
 *               (仕込み途中の次の 1 件が消えないことが、交錯対策の本体)。
 * - `applyEvent` — 必ず runIndex 経由でジョブを引く。ストアの現在値からジョブを推測しない。
 */
export type SkillJobActionNaming = never;
